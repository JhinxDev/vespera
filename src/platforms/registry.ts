export function mergePlatformRegistry(customPlatforms: PlatformDefinition[]): PlatformDefinition[] {
  const map = new Map<string, PlatformDefinition>();
  for (const p of BUILTIN_PLATFORMS) {
    map.set(p.id, p);
  }
  for (const custom of customPlatforms) {
    map.set(custom.id, custom);
  }
  return Array.from(map.values()).sort((a, b) => {
    const aOrder = a.featuredOrder ?? (a.category === "custom" ? 50 : 100);
    const bOrder = b.featuredOrder ?? (b.category === "custom" ? 50 : 100);
    if (aOrder !== bOrder) return aOrder - bOrder;
    return a.name.localeCompare(b.name);
  });
}

export function getBuiltinPlatform(id: string): PlatformDefinition | undefined {
  return BUILTIN_PLATFORMS.find(p => p.id === id);
}
